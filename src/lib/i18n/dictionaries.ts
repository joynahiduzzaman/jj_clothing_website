export type Locale = keyof typeof dictionaries;
export type Dictionary = typeof dictionaries.en;

export function getDictionary(locale: Locale): Dictionary {
  // Both dictionaries.en and dictionaries.bn are declared with `as const` for
  // literal-type precision elsewhere, but that means each locale's strings are
  // distinct literal types — bn's translated strings aren't structurally
  // assignable to en's literal types. The shapes are identical (same keys,
  // values are just translated), so this assertion is safe: it only affects
  // the type checker, not runtime behavior, which was always correct.
  return (dictionaries[locale] ?? dictionaries.en) as Dictionary;
}
